import 'dart:io';

import 'package:chameleon_icons/src/config/chameleon_config.dart';

/// Exception thrown when code generation fails.
class ChameleonGeneratorException implements Exception {
  final String message;
  const ChameleonGeneratorException(this.message);

  @override
  String toString() => 'ChameleonGeneratorException: $message';
}

/// Generates a Dart file exposing typed icon definitions configured in `pubspec.yaml`.
///
/// By default, outputs to `lib/chameleon_icons.g.dart`.
class DartCodeGenerator {
  final ChameleonConfig config;
  final String projectRoot;
  final String outputPath;

  DartCodeGenerator({
    required this.config,
    this.projectRoot = '.',
    this.outputPath = 'lib/chameleon_icons.g.dart',
  });

  /// Generates the Dart file code.
  String generateCode() {
    final buffer = StringBuffer();

    buffer.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
    buffer.writeln('// Generated by chameleon_icons:generate');
    buffer.writeln('');
    buffer.writeln("import 'package:chameleon_icons/chameleon_icons.dart';");
    buffer.writeln('');
    buffer.writeln('/// Strongly-typed icon definitions generated by Chameleon Icons.');
    buffer.writeln('class ChameleonGeneratedIcons {');
    buffer.writeln('  ChameleonGeneratedIcons._();');
    buffer.writeln('');

    // Default icon
    final defaultIcon = config.defaultIcon;
    final defaultLabel = _generateLabel(defaultIcon.key);
    buffer.writeln('  /// Primary default application icon.');
    buffer.writeln('  static const defaultIcon = ChameleonIconDefinition(');
    buffer.writeln("    key: '${_escape(defaultIcon.key)}',");
    buffer.writeln("    id: '${_escape(defaultIcon.name)}',");
    buffer.writeln("    label: '${_escape(defaultLabel)}',");
    buffer.writeln("    assetPath: '${_escape(defaultIcon.imagePath)}',");
    buffer.writeln('    isDefault: true,');
    buffer.writeln('  );');
    buffer.writeln('');

    // Alternate icons individual constants
    for (final alt in config.alternateIcons) {
      final fieldName = _toLowerCamelCase(alt.key);
      final label = _generateLabel(alt.key);

      buffer.writeln("  /// Alternate icon: '${alt.key}'.");
      buffer.writeln('  static const $fieldName = ChameleonIconDefinition(');
      buffer.writeln("    key: '${_escape(alt.key)}',");
      buffer.writeln("    id: '${_escape(alt.name)}',");
      buffer.writeln("    label: '${_escape(label)}',");
      buffer.writeln("    assetPath: '${_escape(alt.imagePath)}',");
      buffer.writeln('    isDefault: false,');
      buffer.writeln('  );');
      buffer.writeln('');
    }

    // List of alternate icons
    buffer.writeln('  /// List of all alternate icon definitions.');
    buffer.writeln('  static const List<ChameleonIconDefinition> alternateIcons = [');
    for (final alt in config.alternateIcons) {
      final fieldName = _toLowerCamelCase(alt.key);
      buffer.writeln('    $fieldName,');
    }
    buffer.writeln('  ];');
    buffer.writeln('');

    // List of all icons
    buffer.writeln('  /// List of all configured icon definitions, starting with the default icon.');
    buffer.writeln('  static const List<ChameleonIconDefinition> all = [');
    buffer.writeln('    defaultIcon,');
    for (final alt in config.alternateIcons) {
      final fieldName = _toLowerCamelCase(alt.key);
      buffer.writeln('    $fieldName,');
    }
    buffer.writeln('  ];');
    buffer.writeln('}');

    return buffer.toString();
  }

  /// Writes the generated code to the output file.
  File generate() {
    final targetPath = projectRoot == '.' ? outputPath : '$projectRoot/$outputPath';
    final targetFile = File(targetPath);

    if (!targetFile.parent.existsSync()) {
      targetFile.parent.createSync(recursive: true);
    }

    final code = generateCode();
    targetFile.writeAsStringSync(code);
    return targetFile;
  }

  static String _generateLabel(String key) {
    if (key.isEmpty) return key;
    // Turn snake_case or kebab-case or camelCase into Title Case
    final words = key
        .replaceAll(RegExp(r'[-_]'), ' ')
        .replaceAllMapped(RegExp(r'([a-z])([A-Z])'), (m) => '${m[1]} ${m[2]}')
        .split(' ')
        .where((w) => w.isNotEmpty);

    return words.map((w) => w[0].toUpperCase() + w.substring(1).toLowerCase()).join(' ');
  }

  static String _toLowerCamelCase(String key) {
    if (key.isEmpty) return key;
    final parts = key.split(RegExp(r'[-_]')).where((p) => p.isNotEmpty).toList();
    if (parts.isEmpty) return key;

    final first = parts.first.toLowerCase();
    final rest = parts.skip(1).map((p) => p[0].toUpperCase() + p.substring(1).toLowerCase()).join();
    return '$first$rest';
  }

  static String _escape(String input) {
    return input.replaceAll(r'\', r'\\').replaceAll("'", r"\'");
  }
}
